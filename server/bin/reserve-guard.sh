#!/bin/sh
# Сторож «магазин может быть только один». Ставится на ВСЕ серверы (основной и
# резервные) перед запуском PocketBase (ExecStartPre) и вызывается копированием
# каждые две минуты.
#
# Смотрит, куда сейчас указывает основной домен. Если на другой сервер — этот
# магазином работать не должен: два PocketBase с одними ключами ботов отнимают
# друг у друга сообщения (Телеграм отвечает 409), оба шлют заказы в МойСклад и
# оба шлют покупателям напоминания. Так бывает, когда старый сервер «оживает»
# после того, как работу уже перенесли на резервный.
#
# Отвечает 0 — можно, 1 — нельзя. Не смог узнать (нет dig, DNS не ответил) —
# разрешает: сторож не должен сам валить живой сайт.
CONF=/opt/venikoff/reserve/conf
[ -f "$CONF" ] || exit 0
. "$CONF"
[ -n "${MY_IP:-}" ] && [ -n "${DOMAINS:-}" ] || exit 0
command -v dig >/dev/null 2>&1 || exit 0
D=${DOMAINS%% *}
# Спрашиваем авторитетный сервер домена: публичные резолверы держат старый ответ в кэше
NS=$(dig +short +time=2 +tries=2 NS "$D" 2>/dev/null | head -1)
IP=$(dig +short +time=2 +tries=2 A "$D" ${NS:+@$NS} 2>/dev/null | grep -E '^[0-9]+(\.[0-9]+){3}$' | tail -1)
[ -n "$IP" ] || exit 0
if [ "$IP" = "$MY_IP" ]; then
  # домен уже здесь — разовое разрешение больше не нужно
  rm -f /opt/venikoff/reserve/force
  exit 0
fi
# promote --now: запустить, не дожидаясь смены записи у регистратора
[ -f /opt/venikoff/reserve/force ] && exit 0
echo "reserve-guard: $D указывает на $IP, а этот сервер $MY_IP — магазин здесь не запускаю" >&2
exit 1
