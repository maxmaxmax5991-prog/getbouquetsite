migrate((app) => {
  const СКЛАД = {
    "Розовые французские розы": "ЛФ-Французская роза пинк мондиаль 60см",
    "Белые французские розы": "ЛФ-Французская роза мондиаль 60см",
    "Красные французские розы": "ЛФ-Французская роза эксплорер 60см",
  };
  Object.keys(СКЛАД).forEach((имя) => {
    try {
      const p = app.findFirstRecordByFilter("products", "name = {:n}", { n: имя });
      p.set("ms_name", СКЛАД[имя]);
      p.set("ms_ids", "{}");
      app.save(p);
    } catch (_) { console.log("ms_name: нет товара", имя); }
  });
}, () => {});
