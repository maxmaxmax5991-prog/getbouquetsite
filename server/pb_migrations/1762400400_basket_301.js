// 301 роза в конструкторе корзин (просьба владельца 06.11.2026).
//
// Цены на такие наборы в прайсе корзин уже были — ступень «от 300 шт» он завёл
// сам. Не хватало только деления на бегунке: у одноголовых он шёл
// 101 · 151 · 201 · 251 · 501 · 1001 и перепрыгивал через всю третью сотню,
// поэтому 301 нельзя было выбрать, хотя цена для неё посчиталась бы.
//
// Вместимость сходится: 301 стебель одноголовых — это 301 место, влезает в
// «ЛФ-Корзина XL» (351). У кустовых и французских место считается за два
// стебля, 301 штука это 602 места — «ЛФ-Корзина XXXL» (801).
migrate((app) => {
  const МАРКИ = {
    "single": "101,151,201,251,301,401,501,1001",
    "kenya": "101,151,201,251,301,401,501,1001",
    "ecuador-premium": "101,151,201,251,301,401,501,1001",
    "french": "51,75,101,151,251,301,501",
    "kustovye-rozy": "51,75,101,151,251,301,501",
    "kustovye-rozy-pionovidnye": "51,75,101,151,251,301,501",
  };
  Object.keys(МАРКИ).forEach((slug) => {
    try {
      const c = app.findFirstRecordByFilter("categories", "slug = {:s}", { s: slug });
      c.set("basket_marks", МАРКИ[slug]);
      app.save(c);
    } catch (err) { console.log("корзины: не поправил деления у", slug, err); }
  });
}, (app) => {
  const БЫЛО = {
    "single": "101,151,201,251,501,1001",
    "kenya": "101,151,201,251,501,1001",
    "ecuador-premium": "101,151,201,251,501,1001",
    "french": "51,75,101,151,251,501",
    "kustovye-rozy": "51,75,101,151,251,501",
    "kustovye-rozy-pionovidnye": "51,75,101,151,251,501",
  };
  Object.keys(БЫЛО).forEach((slug) => {
    try {
      const c = app.findFirstRecordByFilter("categories", "slug = {:s}", { s: slug });
      c.set("basket_marks", БЫЛО[slug]);
      app.save(c);
    } catch (_) {}
  });
});
