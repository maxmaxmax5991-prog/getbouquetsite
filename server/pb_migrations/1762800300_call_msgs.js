// Куда ушёл сигнал о неоплаченном заказе: список «чат → id сообщения».
//
// Сигнал получают все подключённые к боту обзвона, а кнопку нажимает один.
// Раньше правилось только сообщение нажавшего (`cb.message.chat.id`) —
// у остальных карточка так и висела неотвеченной, и один и тот же человек
// получал по два-три звонка подряд. Чтобы погасить карточку у всех, надо
// помнить, в каких чатах и под каким номером она лежит.
//
// Текстовое поле с JSON, а не json-поле: сигнал отмечается запросом мимо
// хуков (обычное сохранение заказа будит уведомления и склад), а писать
// строку запросом проще и предсказуемее, чем json.
migrate((app) => {
  const c = app.findCollectionByNameOrId("orders");
  c.fields.add(new TextField({ name: "call_msgs", max: 2000 }));
  app.save(c);
}, (app) => {
  const c = app.findCollectionByNameOrId("orders");
  c.fields.removeByName("call_msgs");
  app.save(c);
});
