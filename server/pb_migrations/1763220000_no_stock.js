// «Продавать без учёта остатков» — отдельный переключатель на товаре (`no_stock`).
//
// До этого «без учёта» означало отсутствие ключа в карте остатков: нет числа
// у ростовки — продаём сколько угодно. А пустое поле в карточке админки ключ
// и не записывает, поэтому дыра возвращалась после любого сохранения: 15.11
// так продавались без потолка 21 ростовка, до этого Кэти Грандмас, Лидия,
// Пинк Дайменшн.
//
// Теперь: включён переключатель — остатков не считаем вовсе; выключен — нет
// числа значит ноль.
//
// Перенос без сюрпризов: у кого карта остатков сейчас пустая целиком
// (кенийские, французские, гортензии, Эквадор, букеты без ростовок), те и так
// продаются без ограничения — им переключатель включаем. У кого есть хоть одно
// число, недостающие ростовки становятся нулём: это и есть закрываемая дыра.
// Миграция — один запрос, сервер не задерживает.
migrate((app) => {
  const c = app.findCollectionByNameOrId("products");
  c.fields.add(new BoolField({ name: "no_stock" }));
  app.save(c);
  app.db().newQuery(
    "UPDATE products SET no_stock = 1 WHERE stock IS NULL OR TRIM(stock) IN ('', 'null', '{}', '[]')"
  ).execute();
}, (app) => {
  const c = app.findCollectionByNameOrId("products");
  c.fields.removeByName("no_stock");
  app.save(c);
});
