// «Продавать без учёта остатков» (`no_stock`) — и пустое поле остатка теперь ноль.
//
// Было так: в карте остатков нет ключа на ростовку — значит учёта по ней нет,
// продаём сколько закажут. Это удобно для франции, гортензий и эквадорского
// премиума: их считают на складе, а не в карточке. Но ровно это и выстрелило
// 16.11.2026 — сохранение карточки «Фрутти Баблз» из админки отдало пустую
// карту остатков, и сорт сутки продавался без ограничения по количеству.
// Заказов на него не было, но на любом другом сорте это стоило бы отказа
// после оплаты.
//
// Теперь «не считаем» — это отдельный переключатель, который видно в карточке,
// а пустое поле остатка означает ноль: не пересчитали — не продаём.
// Включаем шести карточкам, которые действительно живут без учёта.
migrate((app) => {
  const c = app.findCollectionByNameOrId("products");
  c.fields.add(new BoolField({ name: "no_stock" }));
  app.save(c);
  app.db().newQuery(`UPDATE products SET no_stock = true WHERE id IN (
    'fnezvt1olp7omao',  -- Белые французские розы
    'tu3ecv1v7sr70ow',  -- Красные французские розы
    'czi2wcj9go5a51t',  -- Розовые французские розы
    'yzxgy4udu970fr5',  -- Гортензии Микс
    'uthy85voyh3egx6',  -- Гортензия пинк
    '4q6bbrk89gr2sxo'   -- Эквадор премиум Explorer
  )`).execute();
}, (app) => {
  const c = app.findCollectionByNameOrId("products");
  c.fields.removeByName("no_stock");
  app.save(c);
});
